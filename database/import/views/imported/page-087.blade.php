<h2>What is auto insurance?</h2>
<p>Your auto insurance protects you in the event of a car accident or theft. In exchange for a premium, an insurance carrier pays your losses according to the terms of your policy.</p>
<h2>What does auto insurance cover?</h2>
<p>The amount of coverage can vary depending on the policy you choose. Here are some of the most common coverage options.</p>
<span>
</span>
<h3>
<span>
							Liability						</span>
</h3>
<p>
						If you’re responsible for an accident, liability car insurance protects you.					</p>
<span>
</span>
<h3>
<span>
							Collision						</span>
</h3>
<p>
						Car collision coverage helps pay for repairs if your vehicle is damaged in an accident.					</p>
<span>
</span>
<h3>
<span>
							Comprehensive						</span>
</h3>
<p>
						This covers auto damage caused by incidents other than collisions like theft or severe weather.					</p>
<span>
</span>
<h3>
<span>
							Uninsured and Underinsured						</span>
</h3>
<p>
						Coverage for auto and medical bills if you’re in an accident with an uninsured or underinsured driver.					</p>
<span>
</span>
<h3>
<span>
							Personal Injury						</span>
</h3>
<p>
						Also known as no-fault insurance, this helps pay for medical expenses caused by a car accident.					</p>
<span>
</span>
<h3>
<span>
							Roadside and Rental						</span>
</h3>
<p>
						Added coverage options include rental cars in the event of an accident and roadside assistance.					</p>
<h2>What doesn't auto insurance cover?</h2>
<ul><li>General wear and tear</li><li>Intentional damage</li><li>Routine auto maintenance and repairs</li><li>Drivers not listed on your policy</li><li>Commercial use of your car</li><li>Ridesharing</li><li>Stolen personal items</li></ul>
<h3>Ask the right questions to find the best auto insurance for you</h3>
<p><strong>Questions to consider for yourself</strong></p><ul><li>What is my commute? Where do I park? Consider these day-to-day activities to help determine the amount of coverage you need.</li><li>Who else will be driving my car?</li><li>Do I need any additional coverage like gap or commercial?</li></ul><p><strong>Questions to ask your agent</strong></p><ul><li>Do I qualify for any savings or discounts?</li><li>Are there coverage requirements for my state</li><li>What isn’t covered on my auto insurance policy?</li></ul>
