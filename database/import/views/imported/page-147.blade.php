<span id="more-1209"></span>
<p>For more than 30 years, the U.S. Centers for Disease Control and Prevention (CDC) has been collecting and examining causes of death. The CDC says that they collect and study this information for purposes of determining resources regarding healthcare, but we can also take these statistics to help make our lives better. I was surprised to see that the top 2 <strong>account for about 47% (that’s almost HALF!) of the causes of deaths in the United States.</strong></p>
<h3>1. Heart Disease</h3>
<p><strong>Number of deaths per year:</strong> 633,842<br><strong>Percent of total deaths:</strong> 24.1%</br></p>
<h3>2. Cancer</h3>
<p><strong>Number of deaths per year:</strong> 595,930<br/><strong>Percent of total deaths:</strong> 22.7%</p>
<h3>3. Chronic lower respiratory diseases</h3>
<p><strong>Number of deaths per year:</strong> 155,041<br/><strong>Percent of total deaths:</strong> 5.9%</p>
<h3>4. Accidents (unintentional injuries)</h3>
<p><strong>Number of deaths per year:</strong> 146,571<br/><strong>Percent of total deaths:</strong> 5.6%</p>
<h3>5. Stroke</h3>
<p><strong>Number of deaths per year:</strong> 140,323<br/><strong>Percent of total deaths:</strong> 5.3%</p>
<h3>6. Alzheimer’s disease</h3>
<p><strong>Number of deaths per year:</strong> 110,561<br/><strong>Percent of total deaths:</strong> 3.9%</p>
<h3>7. Diabetes</h3>
<p><strong>Number of deaths per year:</strong> 79,535<br/><strong>Percent of total deaths:</strong> 3.0%</p>
<h3>8. Influenza and pneumonia</h3>
<p><strong>Number of deaths per year:</strong> 57,062<br/><strong>Percent of total deaths:</strong> 2.2%</p>
<h3>9. Kidney disease</h3>
<p><strong>Number of deaths per year:</strong> 49,959<br/><strong>Percent of total deaths:</strong> 1.9%</p>
<h3>10. Suicide</h3>
<p><strong>Number of deaths per year:</strong> 44,193<br/><strong>Percent of total deaths:</strong> 1.7%</p>
<h3>11. Septicemia (blood poisoning)</h3>
<p><strong>Number of deaths per year:</strong> 40,685<br/><strong>Percent of total deaths:</strong> 1.5%</p>
<h3>12. Chronic liver disease and cirrhosis</h3>
<p><strong>Number of deaths per year:</strong> 40,265<br/><strong>Percent of total deaths:</strong> 1.5%</p>
