<h2>Be prepared to bring your pet with you if you decide to evacuate</h2>
<p>Finally, be ready to evacuate with your pet if the situation calls for it.</p>
<p>Your pet’s safety kit should include food, water, medications, and a carrier or leash.</p>
<p>Research pet-friendly evacuation options ahead of time— this could include shelters, hotels, or family and friends outside the evacuation zone.</p>
<p>By following these steps, you can significantly enhance your pet’s safety during hurricane season in Florida.</p>
