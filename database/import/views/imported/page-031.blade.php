<h3>What is not covered by flood insurance?</h3>
<p>Your policy lists specific coverage exclusions and limitations. Please refer to your policy for the complete list.</p>
<h4>Examples of uncovered or excluded losses:</h4>
<ul><li>Damage caused by moisture, mildew, or mold that could have been avoided by the property owner</li><li>Additional living expenses such as temporary housing</li><li>Most self-propelled vehicles such as cars, including their parts</li><li>Property and belongings outside of a building such as trees, plants, shrubs, wells, septic systems, walks, decks, patios, fences, seawalls, hot tubs, and swimming pools</li><li>Financial losses caused by business interruption or loss of use of insured property</li><li>Any damage caused by water flow beneath the earth’s surface (review the exclusions section in your flood insurance policy for specific information on damage caused by seepage or drain or sewer backup)</li><li>The cost of complying with any ordinance of law requiring or regulating the construction, demolition, remodeling, renovation, or repair of property, including removal of any resulting debris</li></ul>
