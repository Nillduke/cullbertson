<h2>What Does Flood Insurance Cover?</h2>
<p>The following provides a general overview of items covered by your flood insurance policy; it is not a comprehensive list. Review your policy for complete coverage and exclusion information.</p>
<section>
<section>
<h3>What is covered by flood insurance?</h3>
<ul><li>The insured building and its foundation</li><li>The electrical systems</li><li>Central air-conditioning equipment, furnaces, and water heaters</li><li>Refrigerators, cooking stoves, and built-in appliances such as dishwashers</li><li>Permanently installed carpeting over an unfinished floor</li><li>Permanently installed paneling, wallboard, bookcases, and cabinets</li><li>Window blinds</li><li>Debris removal</li></ul>
