<h3>How a Flood Claim is Paid</h3><p>Replacement Cost Value (RCV) is the cost to rebuild a<br/> structure using the same kind of material and construction without a deduction for depreciation. Actual Cash Value (ACV) is the cost to replace insured property less the value of physical depreciation.</p><p>If you make a claim and your building coverage is within 80% of the replacement cost of your home, and your home is your principal residence, your claim will be settled based on replacement cost (up to the amount of coverage you purchased). Claims for personal property (contents coverage) are always paid based on ACV. It is important to keep this in mind when determining the amount of coverage to purchase. Talk to your insurance agent about RCV and ACV.</p>
<h3>How to Prevent Future Losses</h3><p>Most NFIP policies include Increased Cost of Compliance (ICC) coverage, which applies when flood damage is severe. If your community declares your home “substantially damaged” or a “repetitive loss property,” you will be required to bring your home up to current community standards. If your damaged building qualifies for ICC coverage, you could receive up to $30,000 to cover the cost to elevate, demolish, or relocate your home. Please refer to Coverage D of your policy and discuss with your insurance agent for further details.</p>
