<h2>What to do after a flood</h2> 

									Anywhere it can rain, it can flood. After experiencing a flood, you should report your loss immediately to <span><a href="/claims/">your insurance company or agent</a></span>.								













<h2>How to File a Flood Insurance Claim</h2>
<p>Report your loss immediately to your insurance agent or to the <a href="/claims/">carrier’s claims office</a> and ask them about an advance payment. Then, prepare for your flood insurance adjuster visit.</p>
