<h2>What is included in my flood insurance policy declaration page? </h2>
<section>
<p>The insurance company that issued your flood insurance policy will provide you with a declaration page which is a part of your annual policy contract.</p><p>The declaration page is usually the first page and is an outline of your flood insurance policy that provides the information you’ll need at the time of a loss.</p><p>Each year when you receive this packet, please make sure to confirm that your policy information is accurate and up to date. Contact your insurance company or agent if any changes are required. This will help to ensure that you have the coverage you need in the event of a flood. By keeping your policy up to date, you can help to protect yourself and your property from the devastating effects of flooding.</p>
<h3>Your declaration page provides some or all of the following information:</h3>
<ul><li>Your policy number</li><li>Policy term</li><li>Billing details</li><li>Insurance company and agent contact information</li><li>Insured property information</li><li>Policyholder information</li><li>Coverage information</li></ul>
</section>
